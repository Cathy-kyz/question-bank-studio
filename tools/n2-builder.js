// Shared by build-n2-bank.js and serve.js: JLPT N2 import JSON -> banks/n2-<key>/question-bank.js, plus banks/manifest.js.
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");

const normalize = (raw, fileName) => {
  global.window = {};
  new Function("window", "indexedDB", fs.readFileSync(path.join(root, "bank-store.js"), "utf8"))(global.window, undefined);
  return global.window.BankStore.normalizeBank(raw, fileName);
};

const writeManifest = () => {
  const keys = fs.readdirSync(path.join(root, "banks"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^n2-\d{6}$/.test(entry.name) && fs.existsSync(path.join(root, "banks", entry.name, "question-bank.js")))
    .map((entry) => entry.name.slice(3)).sort();
  fs.writeFileSync(path.join(root, "banks", "manifest.js"),
    `// Generated by tools/n2-builder.js. Lists the built-in JLPT N2 banks in banks/n2-<key>/.\nwindow.N2_BANK_KEYS = ${JSON.stringify(keys)};\nwindow.N2_BANKS_VERSION = "${Date.now().toString(36)}";\n`);
  return keys;
};

// Throws on invalid format. Returns { bank, warnings } without writing anything when `dryRun`.
const buildN2Bank = (key, raw, names, { dryRun = false } = {}) => {
  const bank = normalize(raw, `n2-${key}.json`);
  const { warnings = [], builtin, ...out } = bank;
  out.id = `n2-${key}`;
  out.name = names;
  if (!dryRun) {
    fs.mkdirSync(path.join(root, "samples"), { recursive: true });
    fs.writeFileSync(path.join(root, "samples", `n2-${key}.json`), JSON.stringify(raw, null, 2) + "\n");
    const dir = path.join(root, "banks", `n2-${key}`);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "question-bank.js"), `window.N2_${key}_BANK = ${JSON.stringify(out, null, 2)};\n`);
    writeManifest();
  }
  return { count: out.questions.length, warnings };
};

module.exports = { buildN2Bank, writeManifest, root };
